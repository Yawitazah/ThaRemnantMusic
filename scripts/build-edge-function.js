// Bundles the app into a single Supabase Edge Function so the team can reach it
// at a public URL without a separate web host.
//
//   npm run build   →  supabase/functions/dashboard/index.ts
//
// The source in public/ stays readable and un-bundled — that is what you edit.
// This script only produces the deployable artifact.

import { build } from 'esbuild';
import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { gzipSync } from 'node:zlib';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT   = fileURLToPath(new URL('..', import.meta.url));
const PUBLIC = join(ROOT, 'public');
const OUT    = join(ROOT, 'supabase', 'functions', 'dashboard');

// supabase-js is loaded from a CDN at runtime — keep it out of the bundle.
const CDN = /^https?:\/\//;
const externalHttp = {
  name: 'external-http',
  setup(b) {
    b.onResolve({ filter: CDN }, args => ({ path: args.path, external: true }));
  },
};

const js = await build({
  entryPoints: [join(PUBLIC, 'js', 'app.js')],
  bundle: true, format: 'esm', minify: true, write: false,
  target: ['es2022'], plugins: [externalHttp], legalComments: 'none',
});

const css = await build({
  entryPoints: [join(PUBLIC, 'css', 'app.css')],
  bundle: true, minify: true, write: false, loader: { '.css': 'css' },
});

const appJs  = js.outputFiles[0].text;
const appCss = css.outputFiles[0].text;

// Rewrite index.html to point at the two bundled assets.
const html = (await readFile(join(PUBLIC, 'index.html'), 'utf8'))
  .replace('<link rel="stylesheet" href="css/app.css">', '<link rel="stylesheet" href="app.css">')
  .replace('<script type="module" src="js/app.js"></script>', '<script type="module" src="app.js"></script>');

// Assets are stored gzipped + base64 so the deployed function stays small, and are
// served as-is with `content-encoding: gzip` — the browser does the decompressing.
const pack = s => gzipSync(Buffer.from(s, 'utf8'), { level: 9 }).toString('base64');

const FILES = {
  '/index.html': { type: 'text/html; charset=utf-8',       gz: pack(html) },
  '/app.css':    { type: 'text/css; charset=utf-8',        gz: pack(appCss) },
  '/app.js':     { type: 'text/javascript; charset=utf-8', gz: pack(appJs) },
};

const src = `// AUTO-GENERATED by scripts/build-edge-function.js — do not edit by hand.
// Serves Tha Remnant Music Group's Label Command Center as a public web app.
// Asset bodies are gzip-compressed and base64-encoded; they are returned with
// content-encoding: gzip, so the browser inflates them.

const FILES: Record<string, { type: string; gz: string }> = ${JSON.stringify(FILES, null, 1)};

function bytes(b64: string): Uint8Array {
  const bin = atob(b64);
  const out = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i++) out[i] = bin.charCodeAt(i);
  return out;
}

const CORS = {
  "access-control-allow-origin": "*",
  "access-control-allow-headers": "authorization, x-client-info, apikey, content-type",
};

Deno.serve((req: Request) => {
  if (req.method === "OPTIONS") return new Response("ok", { headers: CORS });

  const raw = new URL(req.url).pathname;

  // Supabase mounts this at /functions/v1/<name>. Relative asset URLs only resolve
  // correctly when that base path ends in a slash, so redirect the bare form once.
  const bare = raw.match(/^(\\/functions\\/v1\\/[^/]+)$/);
  if (bare) {
    return new Response(null, { status: 308, headers: { ...CORS, location: bare[1] + "/" } });
  }

  let path = raw.replace(/^\\/functions\\/v1\\/[^/]+/, "");
  if (path === "" || path === "/") path = "/index.html";

  const file = FILES[path] ?? FILES["/index.html"];
  return new Response(bytes(file.gz), {
    headers: {
      ...CORS,
      "content-type": file.type,
      "content-encoding": "gzip",
      "vary": "accept-encoding",
      "cache-control": path.endsWith(".html") ? "no-cache" : "public, max-age=300",
    },
  });
});
`;

await mkdir(OUT, { recursive: true });
await writeFile(join(OUT, 'index.ts'), src, 'utf8');

const kb = n => (n / 1024).toFixed(1) + ' KB';
console.log(`js ${kb(appJs.length)} · css ${kb(appCss.length)} · html ${kb(html.length)}`);
console.log(`→ ${join(OUT, 'index.ts')} (${kb(src.length)})`);
